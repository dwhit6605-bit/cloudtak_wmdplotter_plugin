#!/usr/bin/env node
/*
 * Copy WMD PLOTTER's models into this plugin as real ES modules.
 *
 *     node tools/sync-models.mjs [path/to/WMD PLOTTER]      (default: ../WMD PLOTTER)
 *     node tools/sync-models.mjs --check [path]             (exit 1 if out of date)
 *
 * WMD PLOTTER's frontend/js/models/*.js are UMD files: CommonJS for its Node
 * test harness, a global (self.WMDModels) in its browser app. Imported into
 * CloudTAK for their side effect they broke: a bundler that treats modules as
 * free of side effects drops the imports, and one that applies its CommonJS
 * transform sends them down the module.exports branch, so the global is never
 * set ("WMD models failed to load").
 *
 * Each file here is the WMD PLOTTER file, unchanged, between a few generated
 * lines that give it a local `module` and `require` and export what it puts on
 * module.exports. So it is an ES module with a default export, it imports its
 * dependency (dispersion.js) by name, and it never touches a global. The model
 * code is what WMD PLOTTER cross-validates against its Python, unchanged but
 * for trailing whitespace.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '..', 'models');
const args = process.argv.slice(2);
const check = args.includes('--check');
const wmd = resolve(args.find((a) => !a.startsWith('--')) || join(HERE, '..', '..', 'WMD PLOTTER'));
const SRC = join(wmd, 'frontend', 'js', 'models');

export function wrap(name, source) {
  const deps = [...new Set([...source.matchAll(/require\('(\.\/[A-Za-z0-9_]+\.js)'\)/g)].map((m) => m[1]))];
  const lines = [
    `// Generated by tools/sync-models.mjs from WMD PLOTTER frontend/js/models/${name}.`,
    '// Do not edit: change it in WMD PLOTTER and run the sync again. Between the',
    '// generated lines is that file, unchanged but for trailing whitespace.',
    ...deps.map((d, i) => `import dep${i} from '${d}';`),
    'const module = { exports: {} };',
    `const require = (path) => {`,
    `  const dep = { ${deps.map((d, i) => `'${d}': dep${i}`).join(', ')} }[path];`,
    `  if (!dep) throw new Error('models/${name}: no dependency ' + path);`,
    '  return dep;',
    '};',
    '// ---- WMD PLOTTER source begins ----',
    source.replace(/\s+$/, ''),
    '// ---- WMD PLOTTER source ends ----',
    'export default module.exports;',
    '',
  ];
  return lines.join('\n');
}

const TYPES = [
  '// Generated by tools/sync-models.mjs. The models are plain JavaScript; lib/models.ts',
  '// gives the surface the panel uses its types.',
  'declare const model: { [name: string]: unknown };',
  'export default model;',
  '',
].join('\n');

const names = readdirSync(SRC).filter((f) => f.endsWith('.js') && !f.startsWith('._')).sort();
let stale = [];
for (const name of names) {
  const want = wrap(name, readFileSync(join(SRC, name), 'utf8'));
  const dts = name.replace(/\.js$/, '.d.ts');
  for (const [file, content] of [[name, want], [dts, TYPES]]) {
    let have = null;
    try { have = readFileSync(join(OUT, file), 'utf8'); } catch { /* new */ }
    if (have !== content) {
      stale.push(file);
      if (!check) writeFileSync(join(OUT, file), content);
    }
  }
}
if (check) {
  if (stale.length) {
    console.error('models out of date with ' + SRC + ': ' + stale.join(', '));
    process.exit(1);
  }
  console.log('models match ' + SRC);
} else {
  console.log((stale.length ? 'wrote ' + stale.join(', ') : 'already up to date') + ' from ' + SRC);
}
